export const GLYPH_W = 8;
export const GLYPH_H = 8;

/** Bit rows per character code, index 32-126. Bit 7 is the leftmost pixel. */
const TABLE = new Uint8Array(128 * GLYPH_H);

for (const [ch, spec] of Object.entries(GLYPHS)) {
  const code = ch.charCodeAt(0);
  const rows = spec.split('/');
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] ?? '';
    let bits = 0;
    for (let x = 0; x < 6; x++) {
      if (row[x] === '#') bits |= 0x80 >> x;
    }
    TABLE[code * GLYPH_H + y] = bits;
  }
}

/** Rows of a glyph, falling back to '?' for anything unmapped. */
export function glyph(code: number): Uint8Array {
  const c = code >= 32 && code < 127 ? code : 63;
  return TABLE.subarray(c * GLYPH_H, c * GLYPH_H + GLYPH_H);
}

/** True when the glyph has any set pixel at (x, y) within its 8x8 cell. */
export function glyphPixel(code: number, x: number, y: number): boolean {
  if (x < 0 || x >= GLYPH_W || y < 0 || y >= GLYPH_H) return false;
  return (glyph(code)[y] & (0x80 >> x)) !== 0;
}
